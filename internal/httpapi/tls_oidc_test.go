// TestOIDCLoginDerivesHTTPSRedirectOverTLS proves the callback default follows
// the request scheme: on a TLS listener with no redirect_url argument the
// authorization request must carry an https redirect_uri, which is the rule the
// product requires ("callback generated by the browser, https only").
func TestOIDCLoginDerivesHTTPSRedirectOverTLS(t *testing.T) {
	ctx := context.Background()
	idp := oidctest.NewFakeIDP(t)
	defer idp.Server.Close()

	store, _, err := db.OpenWith(ctx, db.Config{
		Driver: dal.SQLite, DSN: filepath.Join(t.TempDir(), "et.db"), AutoAlign: true, Backup: false,
	})
	if err != nil {
		t.Fatalf("store: %v", err)
	}
	defer store.Close()
	cfg := settings.New(store)
	// The fake IdP speaks http on loopback; allow it explicitly.
	_ = store.PutSetting(ctx, "oidc.allow_insecure", "true")
	_ = cfg.MarkInitialized(ctx)
	provider, err := oidc.New(ctx, oidc.Config{
		Issuer:       idp.Server.URL,
		ClientID:     idp.ClientID,
		ClientSecret: "secret",
		Scopes:       []string{"openid"},
	})
	if err != nil {
		t.Fatalf("provider: %v", err)
	}
	manager, err := session.NewManager(store, &session.LocalAuthenticator{Store: store}, session.DefaultPolicy())
	if err != nil {
		t.Fatalf("manager: %v", err)
	}
	api, err := httpapi.New(httpapi.Config{
		Store: store, Sessions: manager, Settings: cfg,
		SecureCookies: true, OIDC: provider, SessionKey: []byte("test-key"),
	})
	if err != nil {
		t.Fatalf("httpapi: %v", err)
	}
	server := httptest.NewTLSServer(api.Handler())
	defer server.Close()

	jar, _ := cookiejar.New(nil)
	client := server.Client()
	client.Jar = jar
	client.CheckRedirect = func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse }

	response, err := client.Get(server.URL + "/api/v1/auth/oidc/login")
	if err != nil {
		t.Fatalf("login: %v", err)
	}
	defer response.Body.Close()
	if response.StatusCode != http.StatusFound {
		t.Fatalf("status = %d, want a redirect to the provider", response.StatusCode)
	}
	location, err := url.Parse(response.Header.Get("Location"))
	if err != nil {
		t.Fatalf("parse location: %v", err)
	}
	redirect := location.Query().Get("redirect_uri")
	if !strings.HasPrefix(redirect, "https://") {
		t.Fatalf("redirect_uri = %q, want an https URL derived from the TLS listener", redirect)
	}
	if !strings.HasSuffix(redirect, "/api/v1/auth/oidc/callback") {
		t.Fatalf("redirect_uri = %q, want the fixed callback path", redirect)
	}
	if !strings.Contains(redirect, strings.TrimPrefix(server.URL, "https://")) {
		t.Fatalf("redirect_uri = %q, want the request host", redirect)
	}
}
