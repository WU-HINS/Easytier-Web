#!/usr/bin/env python3
"""Generate the service/method index table used by the RPC dispatcher.

EasyTier addresses a method by (proto_name, service_name, method_index) where
method_index is the 1-based declaration order inside the service block. That
ordering is a wire contract: if a service gains a method in the middle, every
existing client breaks. Generating the table from the .proto files keeps the Go
implementation and the Rust one provably in step.

Usage: python3 tools/gen_methodindex.py <proto-dir> <output.go>
"""
import os
import re
import sys

SERVICE_RE = re.compile(r"service\s+(\w+)\s*\{(.*?)\n\}", re.S)
RPC_RE = re.compile(r"rpc\s+(\w+)\s*\(\s*([\w.]+)\s*\)\s*returns\s*\(\s*([\w.]+)\s*\)")
PACKAGE_RE = re.compile(r"^package\s+([\w.]+)\s*;", re.M)


def qualify(package: str, type_name: str) -> str:
    if "." in type_name:
        return type_name
    return f"{package}.{type_name}"


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    proto_dir, output = sys.argv[1], sys.argv[2]
    entries = []
    for name in sorted(os.listdir(proto_dir)):
        if not name.endswith(".proto"):
            continue
        body = open(os.path.join(proto_dir, name), encoding="utf-8").read()
        pkg_match = PACKAGE_RE.search(body)
        if not pkg_match:
            continue
        package = pkg_match.group(1)
        for service_name, service_body in SERVICE_RE.findall(body):
            services = []
            for index, (method, req, resp) in enumerate(RPC_RE.findall(service_body), start=1):
                services.append((index, method, qualify(package, req), qualify(package, resp)))
            if not services:
                continue
            entries.append((f"{package}.{service_name}", services))

    lines = [
        "// Code generated by tools/gen_methodindex.py. DO NOT EDIT.",
        "//",
        "// Method indexes are the 1-based declaration order inside each service",
        "// block and are part of the RPC wire contract.",
        "package methodindex",
        "",
        "// Method is one RPC method of a service.",
        "type Method struct {",
        "\tIndex  uint32",
        "\tInput  string",
        "\tOutput string",
        "}",
        "",
        "// Services maps the fully qualified service name to its methods.",
        "var Services = map[string]map[string]Method{",
    ]
    for service, methods in entries:
        lines.append(f"\t\"{service}\": {{")
        for index, method, req, resp in methods:
            lines.append(f"\t\t\"{method}\": {{Index: {index}, Input: \"{req}\", Output: \"{resp}\"}},")
        lines.append("\t},")
    lines.append("}")
    lines.append("")
    lines.append("// Lookup resolves a service and method name.")
    lines.append("func Lookup(service, method string) (Method, bool) {")
    lines.append("\tmethods, ok := Services[service]")
    lines.append("\tif !ok {")
    lines.append("\t\treturn Method{}, false")
    lines.append("\t}")
    lines.append("\tm, ok := methods[method]")
    lines.append("\treturn m, ok")
    lines.append("}")
    lines.append("")
    os.makedirs(os.path.dirname(output), exist_ok=True)
    with open(output, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))
    print(f"wrote {output}: {len(entries)} services, "
          f"{sum(len(m) for _, m in entries)} methods")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
